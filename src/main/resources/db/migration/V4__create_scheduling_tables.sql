CREATE UNIQUE INDEX sales_gym_id_sale_id_key
    ON public.sales (gym_id, sale_id);

CREATE TABLE public.class_schedules (
    schedule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id bigint NOT NULL,
    name character varying(120) NOT NULL,
    description character varying(500),
    weekday smallint NOT NULL,
    start_time time without time zone NOT NULL,
    end_time time without time zone NOT NULL,
    capacity integer NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'ACTIVE',
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT class_schedules_weekday_check CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT class_schedules_time_check CHECK (end_time > start_time),
    CONSTRAINT class_schedules_capacity_check CHECK (capacity > 0),
    CONSTRAINT class_schedules_status_check CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT class_schedules_gym_id_schedule_id_key UNIQUE (gym_id, schedule_id),
    CONSTRAINT class_schedules_gym_fk FOREIGN KEY (gym_id) REFERENCES public.gyms (gym_id)
);

CREATE TABLE public.class_sessions (
    session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id bigint NOT NULL,
    schedule_id bigint NOT NULL,
    starts_at timestamp without time zone NOT NULL,
    ends_at timestamp without time zone NOT NULL,
    capacity integer NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'SCHEDULED',
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT class_sessions_time_check CHECK (ends_at > starts_at),
    CONSTRAINT class_sessions_capacity_check CHECK (capacity > 0),
    CONSTRAINT class_sessions_status_check CHECK (status IN ('SCHEDULED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT class_sessions_gym_id_session_id_key UNIQUE (gym_id, session_id),
    CONSTRAINT class_sessions_schedule_fk FOREIGN KEY (gym_id, schedule_id)
        REFERENCES public.class_schedules (gym_id, schedule_id)
);

CREATE TABLE public.class_reservations (
    reservation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id bigint NOT NULL,
    session_id bigint NOT NULL,
    user_gym_id bigint NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'CONFIRMED',
    source character varying(20) NOT NULL DEFAULT 'ONLINE',
    waitlist_position integer,
    reserved_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    checked_in_at timestamp without time zone,
    checked_in_by_user_gym_id bigint,
    CONSTRAINT class_reservations_status_check CHECK (status IN ('CONFIRMED', 'WAITLISTED', 'CANCELLED', 'ATTENDED', 'NO_SHOW')),
    CONSTRAINT class_reservations_source_check CHECK (source IN ('ONLINE', 'MANUAL')),
    CONSTRAINT class_reservations_waitlist_check CHECK (waitlist_position IS NULL OR waitlist_position > 0),
    CONSTRAINT class_reservations_gym_id_reservation_id_key UNIQUE (gym_id, reservation_id),
    CONSTRAINT class_reservations_attendance_check CHECK (
        (checked_in_at IS NULL AND checked_in_by_user_gym_id IS NULL)
        OR (checked_in_at IS NOT NULL AND checked_in_by_user_gym_id IS NOT NULL)
    ),
    CONSTRAINT class_reservations_session_fk FOREIGN KEY (gym_id, session_id)
        REFERENCES public.class_sessions (gym_id, session_id),
    CONSTRAINT class_reservations_user_gym_fk FOREIGN KEY (gym_id, user_gym_id)
        REFERENCES public.users_gyms (gym_id, user_gym_id),
    CONSTRAINT class_reservations_checked_in_by_fk FOREIGN KEY (gym_id, checked_in_by_user_gym_id)
        REFERENCES public.users_gyms (gym_id, user_gym_id)
);

CREATE TABLE public.class_purchases (
    purchase_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id bigint NOT NULL,
    session_id bigint NOT NULL,
    user_gym_id bigint NOT NULL,
    reservation_id bigint,
    sale_id bigint,
    seller_user_gym_id bigint,
    amount numeric(12,2) NOT NULL,
    payment_method character varying(50) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'PAID',
    source character varying(20) NOT NULL DEFAULT 'MANUAL',
    purchased_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes character varying(500),
    CONSTRAINT class_purchases_amount_check CHECK (amount >= 0),
    CONSTRAINT class_purchases_status_check CHECK (status IN ('PAID', 'REFUNDED', 'VOIDED')),
    CONSTRAINT class_purchases_source_check CHECK (source = 'MANUAL'),
    CONSTRAINT class_purchases_session_fk FOREIGN KEY (gym_id, session_id)
        REFERENCES public.class_sessions (gym_id, session_id),
    CONSTRAINT class_purchases_user_gym_fk FOREIGN KEY (gym_id, user_gym_id)
        REFERENCES public.users_gyms (gym_id, user_gym_id),
    CONSTRAINT class_purchases_reservation_fk FOREIGN KEY (gym_id, reservation_id)
        REFERENCES public.class_reservations (gym_id, reservation_id),
    CONSTRAINT class_purchases_seller_fk FOREIGN KEY (gym_id, seller_user_gym_id)
        REFERENCES public.users_gyms (gym_id, user_gym_id),
    CONSTRAINT class_purchases_sale_fk FOREIGN KEY (gym_id, sale_id)
        REFERENCES public.sales (gym_id, sale_id)
);

